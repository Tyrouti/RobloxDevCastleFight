import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { ROOT, validate, importConcept, select, plan3d, record3d, gallery } from './asset-pipeline.mjs';

test('asset lifecycle and safety gates, offline temporary project', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(),'castle-assets-'));
  try {
    fs.mkdirSync(path.join(root,'docs'));
    fs.copyFileSync(path.join(ROOT,'docs/ASSET_MANIFEST.json'),path.join(root,'docs/ASSET_MANIFEST.json'));
    fs.cpSync(path.join(ROOT,'assets/concepts'),path.join(root,'assets/concepts'),{recursive:true});
    const id = 'human_knight';
    const sf = path.join(root,'assets/concepts/units',id,'selection.json');
    const original = fs.readFileSync(sf,'utf8');
    const set = d => fs.writeFileSync(sf,JSON.stringify(d));
    const get = () => JSON.parse(fs.readFileSync(sf,'utf8'));
    // Exercise a fresh lifecycle in the temporary copy, independent of production approvals.
    const fresh = get();
    fresh.selected = null;
    fresh.status = 'awaiting_concepts';
    fresh.taskIds = {concepts:{A:null,B:null},model3d:null,rigging:null,animations:[]};
    fresh.conceptHashes = {A:null,B:null};
    fresh.approval = {status:'pending'};
    fresh.paidApproval = {status:'not_requested',evidence:null};
    fresh.generationSettings = {concepts:{A:null,B:null},model3d:null};
    for (const variant of ['A','B']) fs.unlinkSync(path.join(root,fresh.paths['variant_'+variant]));
    set(fresh);
    assert.equal(validate(root).assets.length,16);
    assert.throws(() => select(root,id,'A','user'),/E_TWO_CONCEPTS_REQUIRED/);
    assert.throws(() => plan3d(root,id,'unused'),/E_3D_NOT_APPROVED/);
    const png = path.join(root,'real.png');
    fs.writeFileSync(png,Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aUAAAAABJRU5ErkJggg==','base64'));
    importConcept(root,id,'A',png,'test-task-A');
    assert.throws(() => select(root,id,'A','user'),/E_TWO_CONCEPTS_REQUIRED/);
    assert.throws(() => importConcept(root,id,'A',png,'other'),/E_EXISTS/);
    importConcept(root,id,'B',png,'test-task-B');
    select(root,id,'A','user');
    assert.equal(get().approval.status,'approved');
    assert.equal(get().paidApproval.status,'not_requested');
    const approvalFile = path.join(root,'approval.json');
    fs.writeFileSync(approvalFile,JSON.stringify({assetId:id,variant:'A',sha256:get().approval.sha256,status:'approved',approvedBy:'test-user',approvedAt:new Date().toISOString(),evidence:'Offline test fixture only',credits:5,settings:{ai_model:'meshy-t2.5',model_type:'smart-topology',target_polycount:100,should_texture:false,target_formats:['fbx']}}));
    const plan = plan3d(root,id,approvalFile);
    assert.equal(plan.dryRun,true);
    assert.equal(plan.tool,'meshy_image_to_3d');
    select(root,id,'B','user');
    assert.throws(() => plan3d(root,id,approvalFile),/E_PAID_APPROVAL/);
    let d = get(); d.taskIds.model3d = 'test-3d'; set(d);
    assert.throws(() => validate(root),/E_3D_NOT_APPROVED/);
    d.taskIds.model3d = null; set(d);
    const selectedPath = path.join(root,d.paths.variant_B);
    const bytes = fs.readFileSync(selectedPath);
    fs.appendFileSync(selectedPath,'tampered');
    assert.throws(() => validate(root),/E_CONCEPT_CHANGED/);
    fs.writeFileSync(selectedPath,bytes);
    fs.unlinkSync(selectedPath);
    assert.throws(() => validate(root),/E_CONCEPT_MISSING/);
    fs.writeFileSync(selectedPath,bytes);
    select(root,id,'A','user');
    record3d(root,id,approvalFile,'offline-test-3d');
    assert.equal(get().taskIds.model3d,'offline-test-3d');
    validate(root);
    assert.throws(() => select(root,id,'B','user'),/E_LOCKED/);
    assert.throws(() => plan3d(root,id,approvalFile),/E_LOCKED/);
    d = get(); d.paths.variant_A = '../outside.png'; set(d);
    assert.throws(() => validate(root),/E_PATH/);
    d.paths.variant_A = 'assets/concepts/units/human_knight/variant_A.png'; set(d);
    gallery(root);
    const html = fs.readFileSync(path.join(root,'assets/concepts/gallery.html'),'utf8');
    assert.match(html,/A for human_knight/);
    assert.doesNotMatch(html,/<button/);
    fs.writeFileSync(sf,original);
    assert.throws(() => validate(root),/E_CONCEPT_CHANGED/);
  } finally { fs.rmSync(root,{recursive:true,force:true}); }
});
